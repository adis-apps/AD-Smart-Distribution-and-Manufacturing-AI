from sqlalchemy import create_engine, text, inspect
from sqlalchemy.orm import sessionmaker
from app.config import DATABASE_URL

connect_args = {"check_same_thread": False} if DATABASE_URL.startswith("sqlite") else {}
engine = create_engine(DATABASE_URL, future=True, pool_pre_ping=True, connect_args=connect_args)
SessionLocal = sessionmaker(bind=engine, autoflush=False, autocommit=False, future=True)

def init_db():
    with engine.begin() as conn:
        conn.execute(text("""CREATE TABLE IF NOT EXISTS products (
          product_id VARCHAR(40) PRIMARY KEY, product_name VARCHAR(200) NOT NULL,
          category VARCHAR(100), material_cost NUMERIC(12,4) NOT NULL, labor_cost NUMERIC(12,4) NOT NULL,
          overhead_cost NUMERIC(12,4) NOT NULL, freight_cost NUMERIC(12,4) NOT NULL,
          tariff_cost NUMERIC(12,4) NOT NULL DEFAULT 0, min_margin_pct NUMERIC(8,5) NOT NULL DEFAULT 0.15,
          list_price NUMERIC(12,4), unit_of_measure VARCHAR(40))"""))
        conn.execute(text("""CREATE TABLE IF NOT EXISTS customers (
          customer_id VARCHAR(40) PRIMARY KEY, customer_name VARCHAR(200) NOT NULL,
          segment VARCHAR(80), payment_terms INTEGER, credit_hold BOOLEAN DEFAULT FALSE,
          target_margin_pct NUMERIC(8,5) DEFAULT 0.18, annual_revenue NUMERIC(14,2) DEFAULT 0)"""))
        conn.execute(text("""CREATE TABLE IF NOT EXISTS inventory (
          product_id VARCHAR(40) PRIMARY KEY, available_qty INTEGER NOT NULL DEFAULT 0,
          days_on_hand INTEGER NOT NULL DEFAULT 0)"""))
        conn.execute(text("""CREATE TABLE IF NOT EXISTS quote_history (
          quote_id VARCHAR(40) PRIMARY KEY, customer_id VARCHAR(40) NOT NULL, product_id VARCHAR(40) NOT NULL,
          quantity INTEGER NOT NULL, quoted_price NUMERIC(12,4) NOT NULL, competitor_price NUMERIC(12,4),
          won INTEGER NOT NULL, quote_date VARCHAR(20), segment VARCHAR(80))"""))
        conn.execute(text("""CREATE TABLE IF NOT EXISTS product_cost_profiles (
          product_id VARCHAR(40) PRIMARY KEY, setup_cost NUMERIC(12,4) NOT NULL DEFAULT 0,
          engineering_cost NUMERIC(12,4) NOT NULL DEFAULT 0, setup_allocation_qty INTEGER NOT NULL DEFAULT 1,
          cost_to_serve_unit NUMERIC(12,4) NOT NULL DEFAULT 0, capacity_utilization_pct NUMERIC(8,4) NOT NULL DEFAULT 50,
          expedite_premium_pct NUMERIC(8,4) NOT NULL DEFAULT 0.03,
          guaranteed_inventory_premium_pct NUMERIC(8,4) NOT NULL DEFAULT 0.02,
          warranty_premium_pct NUMERIC(8,4) NOT NULL DEFAULT 0.02,
          regulatory_premium_pct NUMERIC(8,4) NOT NULL DEFAULT 0.015,
          sustainability_premium_pct NUMERIC(8,4) NOT NULL DEFAULT 0.01)"""))
        conn.execute(text("""CREATE TABLE IF NOT EXISTS price_agreements (
          agreement_id VARCHAR(40) PRIMARY KEY, customer_id VARCHAR(40) NOT NULL, product_id VARCHAR(40) NOT NULL,
          contract_price NUMERIC(12,4) NOT NULL, start_date VARCHAR(10) NOT NULL, end_date VARCHAR(10) NOT NULL,
          status VARCHAR(20) NOT NULL DEFAULT 'active', notes TEXT)"""))
        conn.execute(text("""CREATE TABLE IF NOT EXISTS quantity_tiers (
          tier_id VARCHAR(40) PRIMARY KEY, product_id VARCHAR(40) NOT NULL, customer_id VARCHAR(40),
          min_quantity INTEGER NOT NULL, max_quantity INTEGER, discount_pct NUMERIC(8,4) NOT NULL DEFAULT 0,
          start_date VARCHAR(10), end_date VARCHAR(10), status VARCHAR(20) NOT NULL DEFAULT 'active')"""))
        conn.execute(text("""CREATE TABLE IF NOT EXISTS quote_decision_audit (
          id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY, customer_id VARCHAR(40), product_id VARCHAR(40),
          quantity INTEGER, recommended_price NUMERIC(12,4), unit_cost NUMERIC(12,4), minimum_price NUMERIC(12,4),
          target_margin_pct NUMERIC(8,4), agreement_id VARCHAR(40), approval_flags TEXT, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP)""") if not DATABASE_URL.startswith("sqlite") else text("""CREATE TABLE IF NOT EXISTS quote_decision_audit (
          id INTEGER PRIMARY KEY AUTOINCREMENT, customer_id TEXT, product_id TEXT, quantity INTEGER,
          recommended_price REAL, unit_cost REAL, minimum_price REAL, target_margin_pct REAL,
          agreement_id TEXT, approval_flags TEXT, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP)"""))
        conn.execute(text("""CREATE TABLE IF NOT EXISTS recommendation_feedback (
          id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY, customer_id VARCHAR(40), product_id VARCHAR(40),
          quantity INTEGER, recommended_price NUMERIC(12,4), selected_price NUMERIC(12,4), outcome VARCHAR(30),
          notes TEXT, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP)""") if not DATABASE_URL.startswith("sqlite") else text("""CREATE TABLE IF NOT EXISTS recommendation_feedback (
          id INTEGER PRIMARY KEY AUTOINCREMENT, customer_id TEXT, product_id TEXT, quantity INTEGER,
          recommended_price REAL, selected_price REAL, outcome TEXT, notes TEXT, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP)"""))

    _migrate()

# Columns added after v0.4. CREATE TABLE IF NOT EXISTS does not alter existing tables,
# so add any missing columns to databases created by earlier versions.
_ADDED_COLUMNS = {"products": {"list_price": "NUMERIC(12,4)", "unit_of_measure": "VARCHAR(40)"}}

def _migrate():
    insp = inspect(engine)
    with engine.begin() as conn:
        for table, cols in _ADDED_COLUMNS.items():
            existing = {c["name"] for c in insp.get_columns(table)}
            for name, ddl in cols.items():
                if name not in existing:
                    conn.execute(text(f"ALTER TABLE {table} ADD COLUMN {name} {ddl}"))
